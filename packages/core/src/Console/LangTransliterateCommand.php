<?php

namespace Codeart\Core\Console;

use Codeart\Core\Translations\SerbianLatinToCyrillic;
use Illuminate\Console\Command;
use Illuminate\Filesystem\Filesystem;

class LangTransliterateCommand extends Command
{
    protected $signature = 'lang:transliterate {--path= : Language folder (default: core\'s) } {--check : Only report files that are out of date}';

    protected $description = 'Generate the sr-Cyrl language files from the sr ones (placeholders such as :name stay untouched)';

    public function handle(Filesystem $files, SerbianLatinToCyrillic $transliterator): int
    {
        $base = (string) ($this->option('path') ?: __DIR__.'/../../resources/lang');
        $stale = [];

        foreach ($files->glob("{$base}/sr/*.php") as $source) {
            $target = "{$base}/sr-Cyrl/".basename($source);
            $generated = $this->render($this->convert($files->getRequire($source), $transliterator));

            if ($files->exists($target) && $files->get($target) === $generated) {
                continue;
            }
            $stale[] = basename($source);
            if (! $this->option('check')) {
                $files->ensureDirectoryExists(dirname($target));
                $files->put($target, $generated);
            }
        }

        if ($this->option('check')) {
            $stale === [] ? $this->components->info('sr-Cyrl files are up to date.') : $this->components->error('Out of date: '.implode(', ', $stale).'. Run lang:transliterate.');

            return $stale === [] ? self::SUCCESS : self::FAILURE;
        }
        $this->components->info($stale === [] ? 'Nothing to do.' : 'Generated: '.implode(', ', $stale).'.');

        return self::SUCCESS;
    }

    /**
     * @param  array<array-key, mixed>  $lines
     * @return array<array-key, mixed>
     */
    private function convert(array $lines, SerbianLatinToCyrillic $transliterator): array
    {
        return array_map(fn (mixed $v): mixed => is_array($v) ? $this->convert($v, $transliterator) : (is_string($v) ? $transliterator->transliterate($v) : $v), $lines);
    }

    /** @param  array<array-key, mixed>  $lines */
    private function render(array $lines): string
    {
        return "<?php\n\n// Generated by `php artisan lang:transliterate` from the sr file. Do not edit by hand.\nreturn ".$this->export($lines, 0).";\n";
    }

    /** @param  array<array-key, mixed>  $value */
    private function export(array $value, int $depth): string
    {
        $pad = str_repeat('    ', $depth + 1);
        $out = "[\n";
        foreach ($value as $key => $item) {
            $k = is_int($key) ? '' : var_export($key, true).' => ';
            $out .= $pad.$k.(is_array($item) ? $this->export($item, $depth + 1) : var_export($item, true)).",\n";
        }

        return $out.str_repeat('    ', $depth).']';
    }
}
